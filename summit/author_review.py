"""Create exact-text authorship review sheets without changing submission packages."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent


def quoted_text(value):
    fence = "`" * (max((len(part) for part in value.split() if set(part) == {"`"}), default=3) + 1)
    return f"{fence}text\n{value}\n{fence}"


def generate():
    output = ROOT / "author-review"
    if output.exists() and any(output.iterdir()):
        raise ValueError("Review sheets already exist; refusing to overwrite author notes.")
    output.mkdir(exist_ok=True)
    manifest = json.loads((ROOT / "drafts/manifest.json").read_text())
    index = [
        "# What to replace before a human-only submission", "",
        "This is an authorship inventory, not an AI-detector diagnosis. The screenshot does not identify particular flagged passages. No scientific answer verification is performed here.", "",
        "## Required work for each question", "",
        "1. **Replace the entire rubric.** All three current criteria (`c1`, `c2`, `c3`) were generated by the assistant in this chat: 78 criteria across 26 tasks. Write your own objective criteria from your independently developed solution. The supplied format requires 3–5 criteria totaling 10 points, exactly one final-answer criterion stating the actual key, and the final criterion carrying the most points.",
        "2. **Establish authorship of the complete question and solution.** Both were copied from older repository files. This migration does not establish who originally wrote them. If they are your independent original work, identify that source; they do not require a cosmetic rewrite solely because they were packaged by software. If they are AI-written or their origin is uncertain, independently develop your own problem and derivation. Merely paraphrasing the existing text does not establish human authorship.",
        "3. **Supply the answer from your own derivation.** Existing keys were transcribed, not independently verified. A numeric answer need not be changed for appearance; submit whatever result your own reasoning establishes, with the requested units and precision.",
        "4. **Review references yourself.** Existing references are copied legacy material and may include textbooks, historical notes or unsupported claims of verification. Supply the references you actually used and that meet the receiving platform's rules.", "",
        "## Exact text for all 26 questions", "",
        "Each linked sheet includes the entire current stem, answer, solution, all three rubric criteria, and references, with their exact JSON field paths. Current text is shown for audit, not as text to disguise. These sheets are snapshots, not submission inputs.", "",
        "| Task | Exact-text replacement sheet | Confirmed AI-written content |",
        "|---|---|---|",
    ]
    for record in manifest["tasks"]:
        slug = record["id"]
        task = json.loads((ROOT / "drafts" / record["task"]).read_text())["task"]
        review = json.loads((ROOT / "drafts" / record["review"]).read_text())
        lines = [
            f"# Author review: {slug}", "",
            "[Back to the full checklist](../AUTHOR_REWRITE_GUIDE.md)", "",
            f"Package input: [task.json](../drafts/{slug}/task.json).", "",
            "These are the exact currently packaged values. This sheet does not identify what the detector flagged or certify authorship. Do not edit wording merely to conceal its origin.", "",
            "## 1. Question — establish origin or independently replace in full", "",
            "Field: `task.questionText`. Copied from legacy source; original authorship is not established by this migration. Includes every assumption, given value, definition and requested output shown below.", "",
            quoted_text(task["questionText"]), "",
            "## 2. Answer — supply the result of your own derivation", "",
            "Field: `task.finalAnswer[0]`. Copied from the legacy key. Keep or correct it according to your own work, not to make it appear different.", "",
            quoted_text(task["finalAnswer"][0]), "",
            f"Current precision metadata: `{json.dumps(task['answerPrecision'])}`. Update it if your question asks for different precision.", "",
            "## 3. Solution — establish origin or independently replace in full", "",
            "Field: `task.solution`. Copied from legacy source; original authorship is not established by this migration. The full derivation, equations, tables and conclusion are included here, not only selected sentences.", "",
            quoted_text(task["solution"]), "",
            "## 4. Rubric — replace every criterion with your own writing", "",
            "Confirmed assistant-generated in this chat. Replace all criterion descriptions, including the final-answer criterion. Choose criteria and weights yourself under the required 10-point format; do not just paraphrase these descriptions.", "",
        ]
        for position, criterion in enumerate(task["rubric"]["criteria"]):
            lines.extend([
                f"### {criterion['id']} — {criterion['points']} points" + (" — final answer" if criterion["isFinalAnswer"] else ""), "",
                f"Field: `task.rubric.criteria[{position}].description`.", "",
                quoted_text(criterion["description"]), "",
            ])
        lines.extend([
            "## 5. References — review and supply your own source record", "",
            "Field: `task.references`. Copied from legacy files. Source metadata is not evidence that the references meet the current submission rules.", "",
            quoted_text(task["references"]), "",
            "## 6. Fields that need no prose rewrite", "",
            "`schema_version`, domain/subdomain identifiers, modality, task type, answer type and JSON syntax are technical metadata. Keep them only where they still describe your task accurately. No image is currently included; if your new task requires one, supply your own permitted image and identify which information it carries. Empty optional answer-variant and wrong-answer lists do not need filler.", "",
            "## Source record", "",
        ])
        lines.extend(f"- [{source['path']}](../../{source['path']})" for source in review["sources"])
        lines.extend([
            "", "## What to return", "",
            "Provide your independently authored question, answer, numbered solution, rubric and references under those five headings. If you retain material you originally wrote, identify that material explicitly. Keep your original notes and derivation; the formatting work does not itself establish eligibility.", "",
            "The assistant can transcribe your equations into LaTeX without changing content, map your supplied text into JSON, synchronize review line arrays and rebuild the ZIP. Neither the packages nor authorship records have been changed by this review-sheet export.", "",
        ])
        (output / f"{slug}.md").write_text("\n".join(lines))
        index.append(f"| {slug} | [Open sheet](author-review/{slug}.md) | All three rubric criteria |")
    index.extend([
        "", "## Replacement and rebuild", "",
        "Return one task at a time with five headings: Question, Answer, Solution, Rubric, References. Identify any retained material that was already your own original work. The exact-text sheets make it possible to specify replacements without editing escaped JSON.", "",
        "After receiving your text, update the package fields and the matching `question_source` / `solution_source` line arrays. Update the provenance to describe which fields were actually replaced; keep the history accurate. Change the answer precision and image fields if your new content requires it, then validate and rebuild the individual ZIP.", "",
        "Do not rerun `complete` to establish human authorship: that command was built for the AI-permitted workflow and stamps AI-assisted rubric metadata. Likewise, `build` uses the old source material and AI rubric definitions. The rebuild workflow must be adjusted when your replacements arrive so it cannot silently restore them.", "",
        "Until replacements and any necessary workflow changes are made, the existing downloadable ZIPs remain the AI-assisted versions. This guide does not change their submission status.", "",
    ])
    (ROOT / "AUTHOR_REWRITE_GUIDE.md").write_text("\n".join(index))
    print(f"Created {len(manifest['tasks'])} exact-text author review sheets and the index.")


if __name__ == "__main__":
    generate()
